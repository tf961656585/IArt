#!/usr/bin/env node
// guard:dialog-sizing
// 规则 1：禁止业务弹窗在 DialogContent 调用点的 className 中出现尺寸相关类。
// 规则 2：canvas 形态 DialogContent 承载图片缩放预览时，必须经 fill prop 表达撑满高度。
// spec: docs/editor/dialog-sizing-contract.md「className 边界」节、「画布形态的场景特化约束」
// 与验收标准第 10 条。
// 尺寸（宽度/高度/溢出/滚动）必须经 form/size props 或 DialogBody variant 表达，
// 不得通过 className 覆盖。dialog.tsx 基础组件内部豁免。
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const DEFAULT_ROOT = process.cwd();
const JSX_EXTENSIONS = new Set([".jsx", ".tsx"]);

const IGNORED_DIRS = new Set([
  ".cache",
  ".git",
  ".next",
  "build",
  "coverage",
  "dist",
  "dist-desktop",
  "node_modules",
  "out",
]);

const IGNORED_PATH_PREFIXES = [
  "_templates/",
  "apps/editor/dist-static/",
  "apps/hub/dist-static/",
];

// dialog.tsx 是基础组件，内部用尺寸类是合法实现。封装层（command/image-preview/
// model-selector）已迁移，不豁免。
const DIALOG_BASE_FILE = "apps/editor/src/components/ui/dialog.tsx";

const parseArgs = (argv) => {
  const args = { root: DEFAULT_ROOT };
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (item === "--root") {
      args.root = path.resolve(argv[index + 1] ?? "");
      index += 1;
    }
  }
  return args;
};

const toPosix = (value) => value.split(path.sep).join("/");

const shouldIgnorePath = (relPath) =>
  IGNORED_PATH_PREFIXES.some(
    (prefix) => relPath === prefix.slice(0, -1) || relPath.startsWith(prefix),
  );

const hasGeneratedMarker = (filePath) => {
  try {
    const head = fs.readFileSync(filePath, "utf8").slice(0, 600);
    return /@generated|自动生成|generated by/i.test(head);
  } catch {
    return false;
  }
};

const isGeneratedFile = (relPath, filePath) => {
  const name = path.basename(relPath);
  return (
    (name.includes(".generated.") && hasGeneratedMarker(filePath)) ||
    name.endsWith(".d.ts") ||
    name.endsWith(".d.cts") ||
    name.endsWith(".d.mts")
  );
};

const walkJsxFiles = (root) => {
  const files = [];
  const stack = [root];

  while (stack.length > 0) {
    const dir = stack.pop();
    if (!dir) continue;

    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }

    for (const entry of entries) {
      const absPath = path.join(dir, entry.name);
      const relPath = toPosix(path.relative(root, absPath));
      if (!relPath || relPath.startsWith("..") || shouldIgnorePath(relPath)) {
        continue;
      }

      if (entry.isDirectory()) {
        if (!IGNORED_DIRS.has(entry.name)) stack.push(absPath);
        continue;
      }

      if (
        entry.isFile() &&
        JSX_EXTENSIONS.has(path.extname(relPath)) &&
        !isGeneratedFile(relPath, absPath) &&
        relPath !== DIALOG_BASE_FILE
      ) {
        files.push({ absPath, relPath });
      }
    }
  }

  return files.sort((left, right) => left.relPath.localeCompare(right.relPath));
};

// 禁止的尺寸类模式。匹配 className 字符串中的 token。
// 响应式前缀（sm:/md:/lg: 等）通过拆分 token 后去掉前缀再匹配。
const FORBIDDEN_PATTERNS = [
  // 宽度
  /^max-w-/,
  /^w-\[/,
  /^w-auto$/,
  /^w-full$/,
  // 高度
  /^max-h-\[/,
  /^h-\[/,
  /^h-full$/,
  // 溢出
  /^overflow-/,
  // 滚动辅助
  /^overscroll-contain$/,
];

const stripResponsivePrefix = (token) => token.replace(/^(sm|md|lg|xl|2xl):/, "");

const findForbiddenTokens = (classNameString) => {
  const tokens = classNameString.split(/\s+/).filter(Boolean);
  const forbidden = [];
  for (const token of tokens) {
    const stripped = stripResponsivePrefix(token);
    if (FORBIDDEN_PATTERNS.some((pattern) => pattern.test(stripped))) {
      forbidden.push(token);
    }
  }
  return forbidden;
};

// 从 className 属性节点提取字符串内容。
// 支持 className="..."（字符串字面量）和 className={cn("...", ...)}（cn/模板）。
const extractClassNameStrings = (attribute) => {
  const initializer = attribute.initializer;
  if (!initializer) return [];

  // className="..." 直接字符串
  if (ts.isStringLiteral(initializer)) {
    return [initializer.text];
  }

  // className={...} 表达式
  if (ts.isJsxExpression(initializer) && initializer.expression) {
    const expr = initializer.expression;

    // className={"..."} 字符串字面量
    if (ts.isStringLiteral(expr)) return [expr.text];

    // className={cn("...", ...)} 或 className={cn("...", variable)}
    // 收集所有字符串字面量参数（cn 的参数 + 嵌套 cn）
    const strings = [];
    const collect = (node) => {
      if (ts.isStringLiteral(node)) {
        strings.push(node.text);
        return;
      }
      if (ts.isCallExpression(node)) {
        for (const arg of node.arguments) collect(arg);
        return;
      }
      if (ts.isConditionalExpression(node)) {
        collect(node.whenTrue);
        collect(node.whenFalse);
        return;
      }
      if (ts.isBinaryExpression(node)) {
        collect(node.left);
        collect(node.right);
      }
    };
    collect(expr);
    return strings;
  }

  return [];
};

const lineOf = (sourceFile, node) =>
  sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile)).line + 1;

const isDialogContentElement = (node) => {
  if (!ts.isJsxOpeningElement(node) && !ts.isJsxSelfClosingElement(node)) {
    return false;
  }
  return node.tagName.getText() === "DialogContent";
};

// 规则 2 口径：图片缩放预览面以百分比高度（h-full / flex-1）撑满父级，前提是父级有确定高度；
// canvas 形态缺 fill 时容器只有 max-h-[90vh]，百分比高度退化为 auto，图片按自身比例撑开后被
// overflow-hidden 裁切（打开即"放大且看不全"）。spec 见 docs/editor/dialog-sizing-contract.md
// 「画布形态的场景特化约束」与 docs/runtime/媒体放大预览交互契约.md「初始尺寸契约」。
const PREVIEW_COMPONENT_NAME = "ZoomableImagePreview";

const getAttribute = (openingElement, name) =>
  openingElement.attributes.properties.find(
    (property) => ts.isJsxAttribute(property) && property.name.getText() === name,
  ) ?? null;

// prop 值的取值文本：裸属性（fill）记 "true"，字符串字面量记 JSON 文本，表达式取其源码文本。
// 属性缺失返回空串（调用方按"未表达"处理）。
const getPropValueText = (attribute) => {
  if (!attribute) return "";
  const initializer = attribute.initializer;
  if (!initializer) return "true";
  if (ts.isStringLiteral(initializer)) return JSON.stringify(initializer.text);
  if (ts.isJsxExpression(initializer) && initializer.expression) {
    return initializer.expression.getText();
  }
  return "";
};

const isCanvasForm = (openingElement) =>
  getPropValueText(getAttribute(openingElement, "form")) === JSON.stringify("canvas");

// fill / fill={true} / fill={表达式} 均视为已表达高度目标；仅显式 fill={false} 视为缺失。
const hasExplicitFill = (openingElement) => {
  const fillAttr = getAttribute(openingElement, "fill");
  if (!fillAttr) return false;
  return getPropValueText(fillAttr) !== "false";
};

// 在 DialogContent 子树内查找图片缩放预览；不下钻嵌套 DialogContent——嵌套弹窗的
// canvas/fill 口径由该节点自身的检查独立负责，避免把内层预览记到外层弹窗上。
const subtreeContainsZoomPreview = (node) => {
  let found = false;
  const visit = (child) => {
    if (found) return;
    const tagName =
      ts.isJsxElement(child)
        ? child.openingElement.tagName
        : ts.isJsxSelfClosingElement(child)
          ? child.tagName
          : null;
    if (tagName !== null) {
      if (
        (ts.isJsxElement(child) && isDialogContentElement(child.openingElement)) ||
        (ts.isJsxSelfClosingElement(child) && isDialogContentElement(child))
      ) {
        return;
      }
      const text = tagName.getText();
      if (text === PREVIEW_COMPONENT_NAME || text.endsWith(`.${PREVIEW_COMPONENT_NAME}`)) {
        found = true;
        return;
      }
    }
    ts.forEachChild(child, visit);
  };
  ts.forEachChild(node, visit);
  return found;
};

const collectFindingsFromNode = (
  node,
  sourceFile,
  relPath,
  classNameFindings,
  fillFindings,
) => {
  if (
    (ts.isJsxElement(node) && isDialogContentElement(node.openingElement)) ||
    (ts.isJsxSelfClosingElement(node) && isDialogContentElement(node))
  ) {
    const openingElement = ts.isJsxElement(node)
      ? node.openingElement
      : node;
    const classNameAttr = getAttribute(openingElement, "className");

    if (classNameAttr) {
      const classNameStrings = extractClassNameStrings(classNameAttr);
      const allForbidden = classNameStrings.flatMap(findForbiddenTokens);

      if (allForbidden.length > 0) {
        classNameFindings.push({
          relPath,
          line: lineOf(sourceFile, openingElement),
          forbidden: allForbidden,
        });
      }
    }

    if (
      ts.isJsxElement(node) &&
      isCanvasForm(openingElement) &&
      !hasExplicitFill(openingElement) &&
      subtreeContainsZoomPreview(node)
    ) {
      fillFindings.push({
        relPath,
        line: lineOf(sourceFile, openingElement),
      });
    }
  }

  ts.forEachChild(node, (child) =>
    collectFindingsFromNode(
      child,
      sourceFile,
      relPath,
      classNameFindings,
      fillFindings,
    ),
  );
};

const collectFindings = (file) => {
  const sourceText = fs.readFileSync(file.absPath, "utf8");
  const sourceFile = ts.createSourceFile(
    file.relPath,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    path.extname(file.relPath) === ".tsx" ? ts.ScriptKind.TSX : ts.ScriptKind.JSX,
  );
  const classNameFindings = [];
  const fillFindings = [];
  collectFindingsFromNode(
    sourceFile,
    sourceFile,
    file.relPath,
    classNameFindings,
    fillFindings,
  );
  return { classNameFindings, fillFindings };
};

const run = () => {
  const args = parseArgs(process.argv.slice(2));
  const files = walkJsxFiles(args.root);
  const classNameFindings = [];
  const fillFindings = [];
  for (const file of files) {
    const found = collectFindings(file);
    classNameFindings.push(...found.classNameFindings);
    fillFindings.push(...found.fillFindings);
  }

  if (classNameFindings.length === 0 && fillFindings.length === 0) {
    console.log(
      `[guard:dialog-sizing] checked ${files.length} JSX files (dialog.tsx exempted).`,
    );
    return 0;
  }

  if (classNameFindings.length > 0) {
    console.error(
      `[guard:dialog-sizing] ${classNameFindings.length} DialogContent call site(s) with forbidden sizing classes in className.`,
    );
    for (const finding of classNameFindings) {
      console.error(
        `- ${finding.relPath}:${finding.line} forbidden tokens: ${finding.forbidden.join(", ")}`,
      );
    }
  }

  if (fillFindings.length > 0) {
    console.error(
      `[guard:dialog-sizing] ${fillFindings.length} canvas DialogContent call site(s) rendering ZoomableImagePreview without fill.`,
    );
    for (const finding of fillFindings) {
      console.error(
        `- ${finding.relPath}:${finding.line} missing fill: 图片缩放预览的父容器必须撑满可用视口；缺 fill 时容器只有 max-h 上限，百分比高度退化为 auto，图片会被 overflow-hidden 裁切。改为传 fill 并让预览面以 flex-1 min-h-0 继承高度。`,
      );
    }
  }

  console.error(
    "Sizing (width/height/overflow) must be expressed via form/size props or DialogBody variant, not className. See docs/editor/dialog-sizing-contract.md.",
  );
  return 1;
};

process.exitCode = run();
