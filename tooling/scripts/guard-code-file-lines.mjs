#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const DEFAULT_ROOT = process.cwd();
const MAX_CODE_FILE_LINES = 1000;

const CODE_EXTENSIONS = new Set([
  ".cjs",
  ".css",
  ".cts",
  ".js",
  ".jsx",
  ".mjs",
  ".mts",
  ".sass",
  ".scss",
  ".ts",
  ".tsx",
]);

const FORBIDDEN_LINE_GATE_BYPASS_PATTERNS = [
  {
    pattern: /eslint-disable(?:-next-line|-line)?[^\n]*\bmax-lines\b/,
    message:
      "Do not disable the max-lines lint gate. Split files by responsibility.",
  },
];

const IGNORED_DIRS = new Set([
  ".cache",
  ".git",
  ".next",
  "build",
  "coverage",
  "dist",
  "dist-desktop",
  "node_modules",
  "out",
]);

const IGNORED_PATH_PREFIXES = [
  "_templates/",
  "apps/backend/native-modules/",
  "apps/editor/dist-static/",
  "apps/hub/dist-static/",
];

const parseArgs = (argv) => {
  const args = {
    root: DEFAULT_ROOT,
    maxLines: MAX_CODE_FILE_LINES,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (item === "--root") {
      args.root = path.resolve(argv[index + 1] ?? "");
      index += 1;
      continue;
    }
    if (item === "--max-lines") {
      args.maxLines = Number(argv[index + 1] ?? MAX_CODE_FILE_LINES);
      index += 1;
    }
  }

  return args;
};

const toPosix = (value) => value.split(path.sep).join("/");

const hasGeneratedMarker = (filePath) => {
  try {
    const head = fs.readFileSync(filePath, "utf8").slice(0, 600);
    return /@generated|自动生成|generated by/i.test(head);
  } catch {
    return false;
  }
};

const isGeneratedFile = (relPath, filePath) => {
  const name = path.basename(relPath);
  return (
    (name.includes(".generated.") && hasGeneratedMarker(filePath)) ||
    name.endsWith(".d.ts") ||
    name.endsWith(".d.cts") ||
    name.endsWith(".d.mts")
  );
};

const shouldIgnorePath = (relPath) =>
  IGNORED_PATH_PREFIXES.some(
    (prefix) => relPath === prefix.slice(0, -1) || relPath.startsWith(prefix),
  );

const isCodeExtension = (relPath) => CODE_EXTENSIONS.has(path.extname(relPath));
const isCodeFile = (relPath, filePath) =>
  isCodeExtension(relPath) && !isGeneratedFile(relPath, filePath);

const countLines = (filePath) => {
  const text = fs.readFileSync(filePath, "utf8");
  if (text.length === 0) return 0;
  const newlineCount = text.split("\n").length;
  return text.endsWith("\n") ? newlineCount - 1 : newlineCount;
};

const findBypassViolations = (files) =>
  files
    .flatMap((file) => {
      const text = fs.readFileSync(file.absPath, "utf8");
      return FORBIDDEN_LINE_GATE_BYPASS_PATTERNS.flatMap((rule) =>
        rule.pattern.test(text) ? [{ ...file, message: rule.message }] : [],
      );
    })
    .sort((left, right) => left.relPath.localeCompare(right.relPath));

const walkCodeFiles = (root) => {
  const files = [];
  const stack = [root];

  while (stack.length > 0) {
    const dir = stack.pop();
    if (!dir) continue;

    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }

    for (const entry of entries) {
      const absPath = path.join(dir, entry.name);
      const relPath = toPosix(path.relative(root, absPath));
      if (!relPath || relPath.startsWith("..") || shouldIgnorePath(relPath))
        continue;

      if (entry.isDirectory()) {
        if (!IGNORED_DIRS.has(entry.name)) {
          stack.push(absPath);
        }
        continue;
      }

      if (entry.isFile() && isCodeExtension(relPath)) {
        files.push({
          absPath,
          relPath,
          entersLineGate: isCodeFile(relPath, absPath),
        });
      }
    }
  }

  return files.sort((left, right) => left.relPath.localeCompare(right.relPath));
};

const run = () => {
  const args = parseArgs(process.argv.slice(2));
  const files = walkCodeFiles(args.root);
  const bypassViolations = findBypassViolations(files);
  const violations = files
    .filter((file) => file.entersLineGate)
    .map((file) => ({ ...file, lines: countLines(file.absPath) }))
    .filter((file) => file.lines > args.maxLines)
    .sort(
      (left, right) =>
        right.lines - left.lines || left.relPath.localeCompare(right.relPath),
    );

  if (bypassViolations.length === 0 && violations.length === 0) {
    const checkedCount = files.filter((file) => file.entersLineGate).length;
    console.log(
      `[guard:code-file-lines] checked ${checkedCount} code files, max ${args.maxLines} lines.`,
    );
    return 0;
  }

  if (bypassViolations.length > 0) {
    console.error(
      `[guard:code-file-lines] ${bypassViolations.length} files try to bypass the line gate.`,
    );
    for (const violation of bypassViolations) {
      console.error(`- ${violation.relPath}: ${violation.message}`);
    }
  }
  if (violations.length > 0) {
    console.error(
      `[guard:code-file-lines] ${violations.length} code files exceed ${args.maxLines} lines.`,
    );
  }
  for (const violation of violations) {
    console.error(`- ${violation.relPath}: ${violation.lines} lines`);
  }
  console.error(
    "Split files by responsibility before adding more code to them.",
  );
  return 1;
};

process.exitCode = run();
