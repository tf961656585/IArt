#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const DEFAULT_ROOT = process.cwd();
const JSX_EXTENSIONS = new Set([".jsx", ".tsx"]);

const IGNORED_DIRS = new Set([
  ".cache",
  ".git",
  ".next",
  "build",
  "coverage",
  "dist",
  "dist-desktop",
  "node_modules",
  "out",
]);

const IGNORED_PATH_PREFIXES = [
  "_templates/",
  "apps/editor/dist-static/",
  "apps/hub/dist-static/",
];

const parseArgs = (argv) => {
  const args = { root: DEFAULT_ROOT };
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (item === "--root") {
      args.root = path.resolve(argv[index + 1] ?? "");
      index += 1;
    }
  }
  return args;
};

const toPosix = (value) => value.split(path.sep).join("/");

const shouldIgnorePath = (relPath) =>
  IGNORED_PATH_PREFIXES.some(
    (prefix) => relPath === prefix.slice(0, -1) || relPath.startsWith(prefix),
  );

const hasGeneratedMarker = (filePath) => {
  try {
    const head = fs.readFileSync(filePath, "utf8").slice(0, 600);
    return /@generated|自动生成|generated by/i.test(head);
  } catch {
    return false;
  }
};

const isGeneratedFile = (relPath, filePath) => {
  const name = path.basename(relPath);
  return (
    (name.includes(".generated.") && hasGeneratedMarker(filePath)) ||
    name.endsWith(".d.ts") ||
    name.endsWith(".d.cts") ||
    name.endsWith(".d.mts")
  );
};

const walkJsxFiles = (root) => {
  const files = [];
  const stack = [root];

  while (stack.length > 0) {
    const dir = stack.pop();
    if (!dir) continue;

    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }

    for (const entry of entries) {
      const absPath = path.join(dir, entry.name);
      const relPath = toPosix(path.relative(root, absPath));
      if (!relPath || relPath.startsWith("..") || shouldIgnorePath(relPath)) {
        continue;
      }

      if (entry.isDirectory()) {
        if (!IGNORED_DIRS.has(entry.name)) stack.push(absPath);
        continue;
      }

      if (
        entry.isFile() &&
        JSX_EXTENSIONS.has(path.extname(relPath)) &&
        !isGeneratedFile(relPath, absPath)
      ) {
        files.push({ absPath, relPath });
      }
    }
  }

  return files.sort((left, right) => left.relPath.localeCompare(right.relPath));
};

const hasAsChildAttribute = (attributes) =>
  attributes.properties.some(
    (property) =>
      ts.isJsxAttribute(property) && property.name.getText() === "asChild",
  );

const isPreservedWhitespaceText = (node, sourceFile) => {
  const raw = node.getFullText(sourceFile);
  return raw.length > 0 && raw.trim().length === 0 && !/[\r\n]/.test(raw);
};

const describeChild = (node, sourceFile) => {
  if (ts.isJsxText(node)) {
    const raw = node.getFullText(sourceFile);
    if (raw.length === 0) return null;
    if (raw.trim().length > 0) return { kind: "text", node };
    if (isPreservedWhitespaceText(node, sourceFile)) {
      return { kind: "single-line whitespace", node };
    }
    return null;
  }

  if (ts.isJsxExpression(node)) {
    if (!node.expression) return null;
    if (
      ts.isBinaryExpression(node.expression) &&
      node.expression.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken
    ) {
      return { kind: "conditional expression", node };
    }
    if (ts.isConditionalExpression(node.expression)) {
      return { kind: "conditional expression", node };
    }
    return { kind: "expression", node };
  }

  if (ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)) {
    return { kind: "element", node };
  }

  if (ts.isJsxFragment(node)) return { kind: "fragment", node };
  return { kind: ts.SyntaxKind[node.kind] ?? "unknown", node };
};

const lineOf = (sourceFile, node) =>
  sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile)).line + 1;

const collectFindingsFromNode = (node, sourceFile, relPath, findings) => {
  if (ts.isJsxElement(node) && hasAsChildAttribute(node.openingElement.attributes)) {
    const children = node.children
      .map((child) => describeChild(child, sourceFile))
      .filter(Boolean);
    const elementLike = children.filter((child) =>
      ["element", "fragment", "expression"].includes(child.kind),
    );
    const invalidChildren = children.filter((child) =>
      ["text", "single-line whitespace", "conditional expression"].includes(
        child.kind,
      ),
    );

    if (
      children.length !== 1 ||
      elementLike.length !== 1 ||
      invalidChildren.length > 0
    ) {
      findings.push({
        relPath,
        line: lineOf(sourceFile, node.openingElement),
        tagName: node.openingElement.tagName.getText(sourceFile),
        children: children.map((child) => child.kind),
      });
    }
  }

  if (
    ts.isJsxSelfClosingElement(node) &&
    hasAsChildAttribute(node.attributes)
  ) {
    findings.push({
      relPath,
      line: lineOf(sourceFile, node),
      tagName: node.tagName.getText(sourceFile),
      children: [],
    });
  }

  ts.forEachChild(node, (child) =>
    collectFindingsFromNode(child, sourceFile, relPath, findings),
  );
};

const collectFindings = (file) => {
  const sourceText = fs.readFileSync(file.absPath, "utf8");
  const sourceFile = ts.createSourceFile(
    file.relPath,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    path.extname(file.relPath) === ".tsx" ? ts.ScriptKind.TSX : ts.ScriptKind.JSX,
  );
  const findings = [];
  collectFindingsFromNode(sourceFile, sourceFile, file.relPath, findings);
  return findings;
};

const run = () => {
  const args = parseArgs(process.argv.slice(2));
  const files = walkJsxFiles(args.root);
  const findings = files.flatMap(collectFindings);

  if (findings.length === 0) {
    console.log(
      `[guard:jsx-aschild-children] checked ${files.length} JSX files.`,
    );
    return 0;
  }

  console.error(
    `[guard:jsx-aschild-children] ${findings.length} invalid asChild usages found.`,
  );
  for (const finding of findings) {
    const children =
      finding.children.length > 0 ? finding.children.join(", ") : "none";
    console.error(
      `- ${finding.relPath}:${finding.line} <${finding.tagName} asChild> children: ${children}`,
    );
  }
  console.error(
    "Radix asChild requires exactly one stable React element child. Move conditions outside the trigger and remove single-line JSX whitespace.",
  );
  return 1;
};

process.exitCode = run();
