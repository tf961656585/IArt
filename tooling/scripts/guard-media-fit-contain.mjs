#!/usr/bin/env node
// guard:media-fit-contain
// 阻断「图片裁切」反模式：媒体元素（img/Image/video/canvas）用百分比 max-height（max-h-full）
// 包在 auto 高度 wrapper（className 含 inline-block）里。
// 百分比 max-height 在自动高度父级下按 CSS 规范解析为 none，高度约束静默失效，
// 媒体只被宽度约束，超出定高舞台容器（overflow-hidden）的部分被裁切，内容观察不可达。
// 正确写法：带叠层交互的舞台媒体用 MediaStageFitBox（显式像素 contain 盒）；
// 无叠层的媒体直挂定高 flex 容器（父级高度确定，max-h-full 才生效）。
// spec: docs/editor/dialog-sizing-contract.md「媒体工具弹窗一屏布局」舞台容器约束尺寸。
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const DEFAULT_ROOT = process.cwd();
const JSX_EXTENSIONS = new Set([".jsx", ".tsx"]);

const IGNORED_DIRS = new Set([
  ".cache",
  ".git",
  ".next",
  "build",
  "coverage",
  "dist",
  "dist-desktop",
  "node_modules",
  "out",
]);

// 死代码 vendored 库（零消费者）不纳入守卫：其内联样式属上游模板产物。
const IGNORED_PATH_PREFIXES = [
  "_templates/",
  "apps/editor/dist-static/",
  "apps/hub/dist-static/",
  "apps/editor/src/components/ai-elements/",
];

const MEDIA_TAGS = new Set([
  "img",
  "Image",
  "NextImage",
  "video",
  "canvas",
  "MediaStageFitBox",
]);

const parseArgs = (argv) => {
  const args = { root: DEFAULT_ROOT };
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (item === "--root") {
      args.root = path.resolve(argv[index + 1] ?? "");
      index += 1;
    }
  }
  return args;
};

const toPosix = (value) => value.split(path.sep).join("/");

const shouldIgnorePath = (relPath) =>
  IGNORED_PATH_PREFIXES.some(
    (prefix) => relPath === prefix.slice(0, -1) || relPath.startsWith(prefix),
  );

const hasGeneratedMarker = (filePath) => {
  try {
    const head = fs.readFileSync(filePath, "utf8").slice(0, 600);
    return /@generated|自动生成|generated by/i.test(head);
  } catch {
    return false;
  }
};

const isGeneratedFile = (relPath, filePath) => {
  const name = path.basename(relPath);
  return (
    (name.includes(".generated.") && hasGeneratedMarker(filePath)) ||
    name.endsWith(".d.ts") ||
    name.endsWith(".d.cts") ||
    name.endsWith(".d.mts")
  );
};

const walkJsxFiles = (root) => {
  const files = [];
  const stack = [root];

  while (stack.length > 0) {
    const dir = stack.pop();
    if (!dir) continue;

    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }

    for (const entry of entries) {
      const absPath = path.join(dir, entry.name);
      const relPath = toPosix(path.relative(root, absPath));
      if (!relPath || relPath.startsWith("..") || shouldIgnorePath(relPath)) {
        continue;
      }

      if (entry.isDirectory()) {
        if (!IGNORED_DIRS.has(entry.name)) stack.push(absPath);
        continue;
      }

      if (
        entry.isFile() &&
        JSX_EXTENSIONS.has(path.extname(relPath)) &&
        !isGeneratedFile(relPath, absPath)
      ) {
        files.push({ absPath, relPath });
      }
    }
  }

  return files.sort((left, right) => left.relPath.localeCompare(right.relPath));
};

const stripResponsivePrefix = (token) => token.replace(/^(sm|md|lg|xl|2xl):/, "");

// 从 className 属性节点提取字符串内容（支持字符串字面量与 cn(...) 表达式）。
const extractClassNameStrings = (attribute) => {
  const initializer = attribute.initializer;
  if (!initializer) return [];

  if (ts.isStringLiteral(initializer)) {
    return [initializer.text];
  }

  if (ts.isJsxExpression(initializer) && initializer.expression) {
    const expr = initializer.expression;
    if (ts.isStringLiteral(expr)) return [expr.text];

    const strings = [];
    const collect = (node) => {
      if (ts.isStringLiteral(node)) {
        strings.push(node.text);
        return;
      }
      if (ts.isCallExpression(node)) {
        for (const arg of node.arguments) collect(arg);
        return;
      }
      if (ts.isConditionalExpression(node)) {
        collect(node.whenTrue);
        collect(node.whenFalse);
        return;
      }
      if (ts.isBinaryExpression(node)) {
        collect(node.left);
        collect(node.right);
      }
    };
    collect(expr);
    return strings;
  }

  return [];
};

const getClassNameAttr = (openingLike) =>
  openingLike.attributes.properties.find(
    (property) =>
      ts.isJsxAttribute(property) && property.name.getText() === "className",
  );

const hasToken = (strings, predicate) =>
  strings.some((text) =>
    text
      .split(/\s+/)
      .filter(Boolean)
      .some((token) => predicate(stripResponsivePrefix(token))),
  );

const mediaUsesPercentMaxHeight = (classNameStrings) =>
  hasToken(classNameStrings, (token) => /^max-h-(full|\[)/.test(token));

const wrapperIsAutoHeight = (classNameStrings) =>
  hasToken(classNameStrings, (token) => token === "inline-block");

// 遍历 JSX 树，携带「最近的 auto 高度 wrapper」上下文：
// 当 auto 高度 wrapper（inline-block）的子树内出现用百分比 max-height 的媒体元素时报违规。
// 只检查 JsxElement / JsxSelfClosingElement，跳过其 openingElement 子节点，避免双重计数。
const collectFindingsFromNode = (node, sourceFile, relPath, findings, inAutoHeightWrapper) => {
  let childAutoHeightContext = inAutoHeightWrapper;

  if (ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)) {
    const opening = ts.isJsxElement(node) ? node.openingElement : node;
    const tag = opening.tagName.getText();
    const attr = getClassNameAttr(opening);
    const classStrings =
      attr && ts.isJsxAttribute(attr) ? extractClassNameStrings(attr) : [];

    if (MEDIA_TAGS.has(tag) && inAutoHeightWrapper && mediaUsesPercentMaxHeight(classStrings)) {
      findings.push({
        relPath,
        line: sourceFile.getLineAndCharacterOfPosition(opening.getStart(sourceFile)).line + 1,
        tag,
      });
    }
    if (wrapperIsAutoHeight(classStrings)) {
      childAutoHeightContext = true;
    }
  }

  ts.forEachChild(node, (child) =>
    collectFindingsFromNode(child, sourceFile, relPath, findings, childAutoHeightContext),
  );
};

const collectFindings = (file) => {
  const sourceText = fs.readFileSync(file.absPath, "utf8");
  const sourceFile = ts.createSourceFile(
    file.relPath,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    path.extname(file.relPath) === ".tsx" ? ts.ScriptKind.TSX : ts.ScriptKind.JSX,
  );
  const findings = [];
  collectFindingsFromNode(sourceFile, sourceFile, file.relPath, findings, false);
  return findings;
};

const run = () => {
  const args = parseArgs(process.argv.slice(2));
  const files = walkJsxFiles(args.root);
  const findings = files.flatMap(collectFindings);

  if (findings.length === 0) {
    console.log(
      `[guard:media-fit-contain] checked ${files.length} JSX files; no percent-max-height media under auto-height wrapper.`,
    );
    return 0;
  }

  for (const finding of findings) {
    console.error(
      `[guard:media-fit-contain] ${finding.relPath}:${finding.line} <${finding.tag}> 用百分比 max-height 包在 inline-block（auto 高度）父级下，高度约束失效会被裁切；改用 MediaStageFitBox 或直挂定高容器。`,
    );
  }
  return 1;
};

process.exitCode = run();
